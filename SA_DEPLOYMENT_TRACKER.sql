-- =============================================================================
-- ORACLE DATABASE DDL SCRIPT
-- Table Name  : SA_DEPLOYMENT_TRACKER
-- Schema Owner: bms (or application schema)
-- Tablespace  : SIT
-- Database    : Oracle Database 19c
--
-- Description : Stores merged latest deployment status per client box 
--               (Frontend and Backend combined, no STACK column).
-- =============================================================================

CREATE TABLE SA_DEPLOYMENT_TRACKER (
    -- Application & Deployment Tracking Columns (Combined F + B)
    DEPLOYMENT_TRACKER_NO   NUMBER(30),
    CLIENT_NAME             VARCHAR2(100 BYTE) NOT NULL,
    FRONTEND_VERSION        VARCHAR2(100 BYTE) DEFAULT 'unknown',
    BACKEND_VERSION         VARCHAR2(100 BYTE) DEFAULT 'unknown',
    STATUS                  VARCHAR2(50 BYTE)  DEFAULT 'pending_first_deploy',
    DEPLOYED_BY             VARCHAR2(100 BYTE) DEFAULT 'system',
    FRONTEND_DEPLOYED_AT    VARCHAR2(100 BYTE),
    BACKEND_DEPLOYED_AT     VARCHAR2(100 BYTE),
    FRONTEND_RUN_ID         VARCHAR2(100 BYTE),
    BACKEND_RUN_ID          VARCHAR2(100 BYTE),
    IS_DEPLOYABLE_TO_CLIENT NUMBER(1)          DEFAULT 0 NOT NULL,
    IS_BACKEND_DEPLOYABLE   NUMBER(1)          DEFAULT 0 NOT NULL,
    ISSUE_NOTES             VARCHAR2(500 BYTE),
    SYNCED_AT               VARCHAR2(100 BYTE),
    UPDATED_AT              VARCHAR2(100 BYTE),

    -- Standard PrideSys ERP Audit & Control Columns
    SS_CREATOR              NUMBER(30),
    SS_CREATED_ON           VARCHAR2(50 BYTE),
    SS_MODIFIER             NUMBER(30),
    SS_MODIFIED_ON          VARCHAR2(50 BYTE),
    COMPANY_NO              NUMBER(30),
    SS_OG_NO                NUMBER(10),
    SS_UPLOADED_ON          VARCHAR2(50 BYTE),
    SS_IS_DELETED           NUMBER(1)          DEFAULT 0,
    SS_IS_UPLOADED          NUMBER(1)          DEFAULT 0
)
TABLESPACE SIT
LOGGING
NOCOMPRESS
NOCACHE
ENABLE ROW MOVEMENT;

-- Performance Indexes on Tablespace SIT
CREATE INDEX IDX_SA_DEPLOY_CLIENT ON SA_DEPLOYMENT_TRACKER (CLIENT_NAME) TABLESPACE SIT;
CREATE INDEX IDX_SA_DEPLOY_FLAG   ON SA_DEPLOYMENT_TRACKER (IS_DEPLOYABLE_TO_CLIENT) TABLESPACE SIT;
CREATE INDEX IDX_SA_DEPLOY_B_FLAG ON SA_DEPLOYMENT_TRACKER (IS_BACKEND_DEPLOYABLE)   TABLESPACE SIT;

-- Constraints
ALTER TABLE SA_DEPLOYMENT_TRACKER ADD CONSTRAINT SA_DEPLOYMENT_TRACKER_PK PRIMARY KEY (DEPLOYMENT_TRACKER_NO);
ALTER TABLE SA_DEPLOYMENT_TRACKER ADD CONSTRAINT SA_DEPLOYMENT_TRACKER_U01 UNIQUE (CLIENT_NAME);
ALTER TABLE SA_DEPLOYMENT_TRACKER ADD CONSTRAINT SA_DEPLOYMENT_TRACKER_C02 CHECK (IS_DEPLOYABLE_TO_CLIENT IN (0, 1));
ALTER TABLE SA_DEPLOYMENT_TRACKER ADD CONSTRAINT SA_DEPLOYMENT_TRACKER_C03 CHECK (IS_BACKEND_DEPLOYABLE IN (0, 1));
